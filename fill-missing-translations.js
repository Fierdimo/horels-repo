/**
 * Fills missing translation keys in EN, DE, FR, IT locale files.
 * Base reference: ES (Spanish).
 * Strategy: deep-merge missing keys into each locale file.
 */

const fs = require('fs');

function deepSet(obj, path, value) {
  const parts = path.split('.');
  let cur = obj;
  for (let i = 0; i < parts.length - 1; i++) {
    if (!cur[parts[i]] || typeof cur[parts[i]] !== 'object') cur[parts[i]] = {};
    cur = cur[parts[i]];
  }
  const last = parts[parts.length - 1];
  if (!(last in cur)) cur[last] = value;
}

function applyMissing(locale, missing) {
  const filePath = `frontend/src/locales/${locale}/translation.json`;
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  const before = JSON.stringify(data).length;
  for (const [path, value] of Object.entries(missing)) {
    deepSet(data, path, value);
  }
  const output = JSON.stringify(data, null, 2);
  fs.writeFileSync(filePath, output, 'utf8');
  console.log(`✅ ${locale}: ${Object.keys(missing).length} keys added`);
}

